const DICTS: Record<string, Record<Key, string>> = { es, "pt-BR": pt, en };

export type BillingKey = Key;

export function useBillingText() {
  const { locale } = useI18n();
  const d = DICTS[locale] ?? es;
  return (k: Key, vars?: Record<string, string | number>) => {
    const s: string = brandText(locale, k, d[k] ?? es[k] ?? k);
    return formatText(locale, s, vars, (v) => (typeof v === "number" ? formatNumber(v, locale) : String(v)));
  };
}

/** Formato de dinero en la moneda dada (sin decimales para montos de plan). */
export function formatMoney(amount: number, currency: string, locale: string, decimals = 2) {
  try {
    return new Intl.NumberFormat(locale === "pt-BR" ? "pt-BR" : locale === "en" ? "en-US" : "es", {
      style: "currency",
      currency,
      maximumFractionDigits: decimals,
      minimumFractionDigits: decimals === 0 ? 0 : undefined,
    }).format(amount);
  } catch {
    return `${amount} ${currency}`;
  }
}
