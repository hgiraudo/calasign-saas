const DICTS: Record<string, Dict> = { es, "pt-BR": ptBR, en };

export type SignatureTextKey = Key;

/** t() de la firma importada y del pase al celular: `gx("import.err.tooLarge", { mb: 10 })`. */
export function useSignatureText() {
  const { locale } = useI18n();
  return useCallback((key: Key, vars?: Record<string, string | number>) => interpolate((DICTS[locale] ?? es)[key] ?? es[key], vars), [locale]);
}
