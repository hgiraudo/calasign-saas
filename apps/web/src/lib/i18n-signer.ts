const DICTS: Record<string, Dict> = { es, "pt-BR": ptBR, en };

export type SignerTextKey = Key;

/** t() del bloque firmante: `sx("otp.text", { dest })`. */
export function useSignerText() {
  const { locale } = useI18n();
  return useCallback(
    (key: Key, vars?: Record<string, string | number>) => {
      const s: string = brandText(locale, key, (DICTS[locale] ?? es)[key] ?? es[key]);
      return interpolate(s, vars);
    },
    [locale],
  );
}
