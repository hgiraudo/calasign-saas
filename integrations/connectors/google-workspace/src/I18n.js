/** "es-419" → "es", "pt-BR" → "pt", otro → "es". */
function langOf_(locale) {
  var l = String(locale || '').toLowerCase().slice(0, 2);
  return CS_MESSAGES[l] ? l : 'es';
}

/** Idioma del evento de Card Service (o el de la cuenta, o español). */
function langFromEvent_(e) {
  var l = e && e.commonEventObject && e.commonEventObject.userLocale;
  if (!l && e && e.userLocale) l = e.userLocale;
  if (!l) {
    try {
      l = Session.getActiveUserLocale();
    } catch (err) {
      l = 'es';
    }
  }
  return langOf_(l);
}

/** Texto traducido con variables {nombre}. */
function t_(lang, key, vars) {
  var dict = CS_MESSAGES[lang] || CS_MESSAGES.es;
  var s = dict[key] !== undefined ? dict[key] : CS_MESSAGES.es[key] !== undefined ? CS_MESSAGES.es[key] : key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, function (m, k) {
      return vars[k] !== undefined ? String(vars[k]) : m;
    });
  }
  return s;
}
