let dict = ES;
let locale = "es";

/** Elige el idioma a partir de Office.context.displayLanguage (p. ej. "pt-BR", "en-US", "es-AR"). */
export function setLanguage(tag) {
  const l = String(tag || "").toLowerCase();
  if (l.startsWith("pt")) {
    dict = PT;
    locale = "pt-BR";
  } else if (l.startsWith("en")) {
    dict = EN;
    locale = "en";
  } else {
    dict = ES;
    locale = "es";
  }
  document.documentElement.lang = locale;
}

/** Locale de CalaSign (es | pt-BR | en) para el sobre. */
export const envelopeLocale = () => locale;

export function t(key, vars) {
  let s = dict[key] ?? ES[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Completa los elementos con data-i18n (textContent, nunca HTML). */
export function applyTranslations(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.getAttribute("data-i18n"));
}
